// ---------------------------------------------------------------------------------------------
// Rust: `vnmf-ffi` → libvnmf_ffi.so (cargo-ndk) and Kotlin bindings (uniffi-bindgen).
// The Rust workspace root is the folder above `android/`. To skip (built separately): -Pvnmf.skipRust=true
// ---------------------------------------------------------------------------------------------

val repoRoot: File = rootProject.projectDir.parentFile
val home: String = System.getProperty("user.home")
val cargo = "$home/.cargo/bin/cargo"
val skipRust = providers.gradleProperty("vnmf.skipRust").map { it.toBoolean() }.getOrElse(false)

fun Exec.rustEnvironment() {
    workingDir = repoRoot
    // Android Studio from Flatpak doesn't see the user's PATH: cargo-ndk and rustc come from ~/.cargo/bin.
    environment("PATH", "$home/.cargo/bin:" + System.getenv("PATH"))
    environment("ANDROID_HOME", androidComponents.sdkComponents.sdkDirectory.get().asFile.absolutePath)
    // NDK path — only right before running: that's also when AGP installs it if needed.
    val ndk = androidComponents.sdkComponents.ndkDirectory
    doFirst { environment("ANDROID_NDK_HOME", ndk.get().asFile.absolutePath) }
}

val cargoNdk = tasks.register<Exec>("cargoNdk") {
    description = "Builds libvnmf_ffi.so for arm64-v8a and x86_64"
    rustEnvironment()
    commandLine(
        cargo, "ndk",
        "--platform", "31",
        "-t", "arm64-v8a", "-t", "x86_64",
        "-o", file("src/main/jniLibs").absolutePath,
        "build", "--release", "-p", "vnmf-ffi",
    )
}

val uniffiBindings = tasks.register<Exec>("uniffiBindings") {
    description = "Generates Kotlin bindings from vnmf-ffi"
    dependsOn(cargoNdk)
    rustEnvironment()
    val out = layout.buildDirectory.dir("generated/uniffi").get().asFile
    // Bindings are read from the metadata of the library itself (any architecture).
    val library = file("src/main/jniLibs/arm64-v8a/libvnmf_ffi.so")
    commandLine(
        cargo, "run", "--release", "-p", "vnmf-ffi", "--features", "cli", "--bin", "uniffi-bindgen", "--",
        "generate", "--library", library.absolutePath, "--language", "kotlin", "--no-format", "--out-dir", out.absolutePath,
    )
}

if (!skipRust) {
    tasks.named("preBuild") { dependsOn(uniffiBindings) }
}
