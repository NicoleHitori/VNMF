const DICTS = { en, uk };

const STORAGE_KEY = 'vnmf-language';

function initial() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved in DICTS) return saved;
  } catch {
    /* storage unavailable */
  }
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = l?.slice(0, 2).toLowerCase();
    if (code in DICTS) return code;
  }
  return 'en';
}

export const i18n = $state({ lang: initial() });

/** Switches the interface language; remembered in this browser (also before signing in). */
export function setLanguage(lang) {
  if (!(lang in DICTS)) return;
  i18n.lang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* storage unavailable */
  }
}

export function t(key, vars = {}) {
  const lang = i18n.lang in DICTS ? i18n.lang : 'en';
  let value = DICTS[lang][key] ?? en[key];
  if (value === undefined) return key.includes('.') ? key.slice(key.lastIndexOf('.') + 1) : key;
  if (typeof value === 'object') value = value[new Intl.PluralRules(lang).select(Number(vars.n ?? 0))] ?? value.other;
  return value.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`).toString());
}
